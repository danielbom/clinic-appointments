import path from 'node:path'
import { type Writable, WriteStr } from '../../lib/writable'
import { VALIDATIONS_PATH } from './_config'
import { collectApi, refToSchemaId } from './_internal'

function hasBodyOrQuery(actions: Record<string, { body?: unknown; query?: unknown }>): boolean {
  for (const key in actions) {
    const action = actions[key]
    if (!action) throw new Error(`action ${key} not found`)

    if (action.body || action.query) return true
  }
  return false
}

function generateAjvValidations(w: Writable) {
  const stats = { validationsCount: 0 }
  const api = collectApi()

  w.write(`// Code generated by ${path.basename(import.meta.filename)} - DO NOT EDIT.\n\n`)
  w.write("import { compile as c } from '../core/ajv'\n")
  w.write("import type * as types from './types'\n")
  w.write('\n')
  w.write('export const validations = {\n')

  for (const resource of Object.keys(api).sort()) {
    const route = api[resource]
    if (!route) throw new Error(`route ${resource} not found`)
    if (!hasBodyOrQuery(route.actions)) continue

    w.write(`  ${resource}: {\n`)
    for (const action in route.actions) {
      const endpoint = route.actions[action]
      if (!endpoint) throw new Error(`endpoint ${resource}.${action} not found`)

      if (!endpoint.body) continue

      w.write(`    ${action}: {\n`)
      if (endpoint.body) {
        const id = refToSchemaId(endpoint.body.content['application/json'].schema.$ref)
        w.write(`      body: c<types.api.${resource}.${action}.body>({\n`)
        w.write(`        $ref: '${id}',\n`)
        w.write(`      }),\n`)
        stats.validationsCount++
      }
      w.write('    },\n')
    }
    w.write('  },\n')
  }
  w.write('}\n')

  return stats
}

const w = new WriteStr()
const stats = generateAjvValidations(w)
if (stats.validationsCount > 0) {
  VALIDATIONS_PATH.writeText(w.value())
} else {
  VALIDATIONS_PATH.writeText('')
}
console.log(`ok: validations file: ${VALIDATIONS_PATH} count: ${stats.validationsCount}`)
